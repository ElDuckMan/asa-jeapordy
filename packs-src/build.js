#!/usr/bin/env node
/* Builds public/js/packs/*.js (and sample-game.js = Classic) from /home/claude/packs-src. */
'use strict';
const fs = require('fs'), path = require('path');
const SRC = __dirname, OUT = path.join(__dirname, '..', 'public', 'js');
const read = f => JSON.parse(fs.readFileSync(path.join(SRC, f), 'utf8'));
fs.mkdirSync(path.join(OUT, 'packs'), { recursive: true });

/* Classic = original rounds as Board A, each followed by its Board B (if written). */
const A = read('classic-a.json');
const B = fs.existsSync(path.join(SRC, 'classic-b.json')) ? read('classic-b.json').rounds : [];
const rounds = [];
for (const r of A.rounds) {
  const group = r.group || r.name;
  rounds.push(Object.assign({}, r, { group, variant: 'A' }));
  const b = B.find(x => x.group === group);
  if (b) rounds.push(Object.assign({}, b, { group, variant: 'B', name: r.name }));
}
const classic = { title: 'ASA Jeopardy', edition: 'Classic Edition', rounds };
fs.writeFileSync(path.join(OUT, 'sample-game.js'),
  '/* ASA Classic pack (also the default game). Generated by packs-src/build.js. */\nwindow.SAMPLE_GAME = ' + JSON.stringify(classic, null, 1) + ';\n');
fs.writeFileSync(path.join(OUT, 'packs', 'classic.js'),
  "AsaPacks.add({ id: 'classic', name: 'ASA Classic', blurb: 'The original pan-Asian set, plus a hard tier with hints.', game: window.SAMPLE_GAME });\n");
console.log('classic:', rounds.length, 'rounds (' + B.length + ' Board B)');

for (const id of ['standard', 'east-asia', 'south-asia', 'africa']) {
  const f = id + '.json';
  if (!fs.existsSync(path.join(SRC, f))) { console.log(id + ': not written yet'); continue; }
  const p = read(f);
  fs.writeFileSync(path.join(OUT, 'packs', id + '.js'), '/* Generated by packs-src/build.js */\nAsaPacks.add(' + JSON.stringify(p, null, 1) + ');\n');
  console.log(id + ':', p.game.rounds.length, 'rounds');
}
