#!/usr/bin/env node
/* Builds public/js/packs/*.js (and sample-game.js = Classic) from the JSON sources in this folder.
 * Extra boards live in <pack>-c.json ({"rounds":[…]} with variant "C"); they are merged after A/B of each round. */
'use strict';
const fs = require('fs'), path = require('path');
const SRC = __dirname, OUT = path.join(__dirname, '..', 'public', 'js');
const has = f => fs.existsSync(path.join(SRC, f));
const read = f => JSON.parse(fs.readFileSync(path.join(SRC, f), 'utf8'));
fs.mkdirSync(path.join(OUT, 'packs'), { recursive: true });

/* Merge rounds: keep the first-appearance order of groups; inside a group, order by variant letter. */
function merge(...lists) {
  const order = [], by = new Map();
  for (const list of lists) for (const r of list) {
    const g = r.group || r.name;
    if (!by.has(g)) { by.set(g, []); order.push(g); }
    by.get(g).push(r);
  }
  return order.flatMap(g => by.get(g).sort((a, b) => (a.variant || '').localeCompare(b.variant || '')));
}
const variants = rounds => [...new Set(rounds.map(r => r.variant))].sort().join('');
const write = (id, pack) => fs.writeFileSync(path.join(OUT, 'packs', id + '.js'), '/* Generated by packs-src/build.js */\nAsaPacks.add(' + JSON.stringify(pack, null, 1) + ');\n');

/* Classic = original rounds (Board A) + B + C. */
const A = read('classic-a.json').rounds.map(r => Object.assign({}, r, { group: r.group || r.name, variant: 'A' }));
const extras = ['classic-b.json', 'classic-c.json'].filter(has).map(f => read(f).rounds.map(r => {
  const base = A.find(a => a.group === r.group);
  return Object.assign({}, r, { name: base ? base.name : r.name });
}));
const classic = { title: 'ASA Jeopardy', edition: 'Classic Edition', rounds: merge(A, ...extras) };
fs.writeFileSync(path.join(OUT, 'sample-game.js'),
  '/* ASA Classic pack (also the default game). Generated by packs-src/build.js. */\nwindow.SAMPLE_GAME = ' + JSON.stringify(classic, null, 1) + ';\n');
fs.writeFileSync(path.join(OUT, 'packs', 'classic.js'),
  "AsaPacks.add({ id: 'classic', name: 'ASA Classic', blurb: 'The original pan-Asian set, plus a hard tier with hints.', game: window.SAMPLE_GAME });\n");
console.log('classic:', classic.rounds.length, 'rounds, boards', variants(classic.rounds));

for (const id of ['standard', 'east-asia', 'south-asia', 'africa']) {
  if (!has(id + '.json')) { console.log(id + ': missing'); continue; }
  const p = read(id + '.json');
  if (has(id + '-c.json')) p.game.rounds = merge(p.game.rounds, read(id + '-c.json').rounds);
  write(id, p);
  console.log(id + ':', p.game.rounds.length, 'rounds, boards', variants(p.game.rounds));
}

/* Church pack: boards A–B and C–D come from two files. */
const churchParts = ['church-ab.json', 'church-cd.json'].filter(has).map(f => read(f).rounds);
if (churchParts.length) {
  const rounds = merge(...churchParts);
  write('church', {
    id: 'church', name: 'Church', blurb: 'Bible & church trivia: Old and New Testament, worship music, Christian film and church history.',
    game: { title: 'Bible Jeopardy', edition: 'Church Edition', presenter: 'Church Game Night', rounds }
  });
  console.log('church:', rounds.length, 'rounds, boards', variants(rounds));
} else console.log('church: missing');

/* Party pack: one round group per mode, with sets A = General, B = Asia, C = Church. */
const partyFiles = ['party-a.json', 'party-b.json', 'party-c.json'].filter(has);
if (partyFiles.length) {
  const P = Object.assign({}, ...partyFiles.map(read));
  const SETS = [['general', 'A', 'General'], ['asia', 'B', 'Asia'], ['church', 'C', 'Church']];
  const MODES = [
    ['speed', 'Speed Quiz', { type: 'speed', points: 500, timer: 15 }],
    ['emoji', 'Emoji Decode', { type: 'lightning', duration: 90, points: 100, penalty: false }],
    ['closest', 'Closest Guess', { type: 'closest', points: 300, timer: 30 }],
    ['fakeout', 'Fake Out', { type: 'fakeout', truthPts: 200, foolPts: 100, timer: 60, voteTimer: 30 }],
    ['survey', 'Survey Says', { type: 'survey', points: 10, timer: 45 }],
    ['truths', 'Two Truths & a Lie', { type: 'truths', points: 200, timer: 30 }],
    ['wheel', 'Wheel', { type: 'wheel' }],
    ['draw', 'Draw & Guess', { type: 'draw', points: 200, timer: 75 }],
    ['tune', 'Name That Tune', { type: 'bonus', points: 200, timer: 30 }]
  ];
  /* Name That Tune songs: tune-<set>.json → P.tune[set] */
  for (const [set] of SETS) if (has(`tune-${set}.json`)) (P.tune = P.tune || {})[set] = read(`tune-${set}.json`).items;
  const rounds = [];
  for (const [mode, name, base] of MODES) {
    if (mode === 'truths') { rounds.push(Object.assign({ name, group: name, variant: '', label: '' }, base)); continue; }
    if (!P[mode]) { console.log('party: missing', mode); continue; }
    for (const [set, variant, label] of SETS) {
      const items = P[mode][set] || [];
      const r = Object.assign({ name: `${name}: ${label}`, group: name, variant, label }, base);
      if (mode === 'emoji') r.questions = items.map(x => ({ q: x.q, a: x.a, hint: x.hint || '' }));
      else if (mode === 'tune') r.questions = items.map(x => ({ q: '🎵 Name this song!', a: `${x.title} (${x.artist})`, options: x.options, correct: x.correct,
        media: { type: 'youtube', url: `https://www.youtube.com/watch?v=${x.id}${x.start ? `&t=${x.start}` : ''}` } }));
      else r.items = items;
      rounds.push(r);
    }
  }
  write('party', {
    id: 'party', name: 'Party Games', blurb: 'Speed Quiz, Emoji Decode, Closest Guess, Fake Out, Survey Says, Two Truths & a Lie, Wheel, Draw & Guess, Name That Tune.',
    game: { title: 'ASA Game Night', edition: 'Party Games', rounds }
  });
  console.log('party:', rounds.length, 'rounds');
}
